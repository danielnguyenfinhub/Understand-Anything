#!/usr/bin/env node
/**
 * Emit the two reference artifacts for the Mercury field & UI-enum model:
 *
 *   docs/mercury-api/ui-enum-bindings.json    — machine-readable; what a form
 *       builder consumes. Every enum with its values, the UI control it implies,
 *       the field(s) that carry it, the free-text fields that are constrained in
 *       practice, the format traps that aren't enums, and a field → control index.
 *
 *   docs/mercury-api/field-and-enum-reference.md — the same model for humans,
 *       including the full per-schema field inventory.
 *
 * Both are derived from docs/mercury-api/mercury-api.openapi.json and
 * mercury-api.enumcatalog.json; see scripts/lib/mercury-field-enum-model.mjs.
 * Neither should be hand-edited — re-run this instead.
 *
 * Usage:
 *   node scripts/generate-mercury-field-enum-reference.mjs
 */

import { writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { buildFieldEnumModel } from "./lib/mercury-field-enum-model.mjs";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const docsDir = resolve(repoRoot, "docs/mercury-api");
const model = buildFieldEnumModel();

if (model.unmatchedInlineEnums.length > 0) {
  console.error(`✗ inline enums with no named counterpart in the catalog: ${model.unmatchedInlineEnums.join(", ")}`);
  console.error("  Add them to mercury-api.enumcatalog.json, or the field→enum binding will be lost.");
  process.exit(1);
}

// ───────────────────────── JSON ─────────────────────────

// Field-first index: "Schema.field" → the control to render. Saves every
// consumer from re-deriving the inverse of the enum → fields mapping.
const fieldIndex = {};
for (const e of model.enums) {
  for (const f of e.boundFields) {
    fieldIndex[f] = { enum: e.name, control: e.control, optionCount: e.valueCount, apiValidated: true };
  }
}
for (const s of model.softEnumFields) {
  const catalogEnum = s.catalog?.[0] ?? null;
  fieldIndex[s.field] = {
    enum: catalogEnum,
    control: s.control,
    optionCount: s.values?.length ?? (catalogEnum ? (model.enums.find((e) => e.name === catalogEnum)?.valueCount ?? null) : null),
    apiValidated: false,
    note: s.note,
  };
}

const json = {
  $comment:
    "Generated by scripts/generate-mercury-field-enum-reference.mjs — do not edit by hand. " +
    "apiValidated:false means the contract types the field as a plain string; the values are a catalog, not a constraint.",
  generatedFrom: model.generatedFrom,
  stats: model.stats,
  controlRules: model.controlRules,
  enums: model.enums,
  softEnumFields: model.softEnumFields,
  fieldHazards: model.fieldHazards,
  fieldIndex,
};

const jsonPath = resolve(docsDir, "ui-enum-bindings.json");
mkdirSync(docsDir, { recursive: true });
writeFileSync(jsonPath, JSON.stringify(json, null, 2) + "\n");

// ───────────────────────── Markdown ─────────────────────────

const s = model.stats;
const esc = (v) => String(v).replace(/\|/g, "\\|");
const code = (v) => `\`${String(v).replace(/`/g, "")}\``;
const codeList = (arr) => (arr.length === 0 ? "—" : arr.map(code).join(", "));

const md = [];
const w = (...lines) => md.push(...lines);

w(
  "# Mercury API — field & UI-enum reference",
  "",
  "<!-- Generated by scripts/generate-mercury-field-enum-reference.mjs — do not edit by hand. -->",
  "",
  `Derived from \`mercury-api.openapi.json\` (${model.generatedFrom.openapi}) and`,
  `\`mercury-api.enumcatalog.json\` (generated ${model.generatedFrom.enumCatalogGeneratedAt}), both committed`,
  "alongside this file. The machine-readable form of everything below is",
  "[`ui-enum-bindings.json`](./ui-enum-bindings.json).",
  "",
  "| | |",
  "|---|---|",
  `| Path templates / operations | ${s.paths} / ${s.operations} |`,
  `| Object schemas / fields | ${s.objectSchemas} / ${s.fields} |`,
  `| Enums / total values | ${s.enums} / ${s.enumValues} |`,
  `| Enums the contract enforces | ${s.apiValidatedEnums}, binding ${s.enumBoundFields} fields |`,
  `| Enums that are catalogs only | ${s.catalogOnlyEnums} — the fields they describe are free text |`,
  `| Free-text fields constrained in practice | ${s.softEnumFields} |`,
  `| Field-hazard groups (format, casing, writability) | ${s.hazardGroups} |`,
  "",
  "## The one distinction that matters",
  "",
  "\"Has a documented list of values\" and \"rejects values outside that list\" are",
  "independent properties, and this API separates them sharply.",
  "",
  `${s.apiValidatedEnums} enums are written into the contract: the wire will refuse anything else, so a`,
  "closed dropdown is safe.",
  "",
  `${s.catalogOnlyEnums} are catalogs of values observed in live branch data against fields the contract`,
  "types as plain strings — `Opportunity.status`, `Category.categoryName`. They look",
  "exactly like enums and are documented next to them, but nothing enforces them. A",
  "closed dropdown here breaks the first time the branch adds a pipeline stage.",
  "",
  `A further ${s.softEnumFields} fields sit in the same position with smaller or undocumented catalogs.`,
  "Every one of them is listed under [Soft enums](#soft-enums-string-on-the-wire-constrained-in-practice).",
  "",
  "## Choosing a control",
  "",
  "| Control | Options | Why |",
  "|---|---|---|",
);
for (const r of model.controlRules) {
  w(`| \`${r.control}\` | ${r.maxOptions === null ? "> 60" : `≤ ${r.maxOptions}`} | ${esc(r.rationale)} |`);
}
w(
  "",
  "Two things override the count. A free-text field needs a creatable control however",
  "short its catalog. And `AssetLiabilityType` — four values, nominally a `select` —",
  "decides which half of the form exists rather than recording a choice, so it is",
  "worth treating as a mode switch rather than a field.",
  "",
  "## Enums",
  "",
  "| Enum | Values | Control | Enforced | Carried by |",
  "|---|---:|---|---|---|",
);
for (const e of model.enums) {
  const carried = e.isApiValidated ? codeList(e.boundFields) : `_(catalog for ${codeList(e.softFor)})_`;
  w(
    `| [\`${e.name}\`](#${e.name.toLowerCase()}) | ${e.valueCount} | \`${e.control}\` | ${e.isApiValidated ? "yes" : "**no**"} | ${carried} |`,
  );
}
w("", "---", "");

for (const e of model.enums) {
  w(
    `### ${e.name}`,
    "",
    `**${e.label}** · ${e.valueCount} values · suggested control \`${e.control}\``,
    "",
    e.isApiValidated
      ? `Enforced by the contract. Carried by ${codeList(e.boundFields)}.`
      : `**Not enforced by the contract** — a catalog of live values for ${codeList(e.softFor)}, which ${e.softFor.length === 1 ? "is" : "are"} typed as a plain string. Render it creatable.`,
    "",
    `_${esc(e.controlRationale)}_`,
    "",
  );
  if (e.hazards.length > 0) {
    for (const h of e.hazards) w(`> ⚠️ ${h}`, ">");
    w("");
  }
  w("<details><summary>Values</summary>", "", ...e.values.map((v) => `- \`${v}\``), "", "</details>", "");
}

w(
  "## Soft enums — string on the wire, constrained in practice",
  "",
  "The contract types each of these as a plain string, so nothing rejects an",
  "unexpected value. Offer the known values; keep the control creatable.",
  "",
  "| Field | Control | Known values | Note |",
  "|---|---|---|---|",
);
for (const sf of model.softEnumFields) {
  const known = sf.values
    ? codeList(sf.values)
    : sf.catalog
      ? `_from ${codeList(sf.catalog)}_`
      : "_none documented_";
  w(`| \`${sf.field}\` | \`${sf.control}\` | ${known} | ${esc(sf.note)} |`);
}

w(
  "",
  "## Field hazards that aren't enums",
  "",
  "A form gets these wrong regardless of how well it handles the value sets.",
  "",
);
for (const h of model.fieldHazards) {
  w(
    `### ${h.id.replace(/-/g, " ")} · ${h.severity}`,
    "",
    esc(h.note),
    "",
    `**Affects:** ${codeList(h.fields)}`,
    "",
  );
}

w(
  "## Field inventory",
  "",
  `All ${s.fields} fields across ${s.objectSchemas} object schemas, as the contract declares them.`,
  "The **Control** column is filled where the field resolves to a UI control —",
  "either through an enum or through the soft-enum table above.",
  "",
);
for (const schema of model.schemas) {
  const enumFields = schema.fields.filter((f) => f.enum).length;
  w(
    `### ${schema.name}`,
    "",
    `${schema.fields.length} fields${enumFields > 0 ? `, ${enumFields} enum-bound` : ""}.`,
    "",
    "| Field | Type | Enum | Control |",
    "|---|---|---|---|",
  );
  for (const f of schema.fields) {
    const ref = `${schema.name}.${f.name}`;
    const idx = fieldIndex[ref];
    const enumCell = f.enum ? `\`${f.enum}\`` : idx?.enum ? `_${idx.enum}_ (unenforced)` : "—";
    const controlCell = idx ? `\`${idx.control}\`` : "—";
    w(`| \`${f.name}\` | ${esc(f.type)} | ${enumCell} | ${controlCell} |`);
  }
  w("");
}

w(
  "## What this does not establish",
  "",
  "The census behind the contract was read-only, so the following are still open and",
  "need sandbox write probes before a form can rely on them:",
  "",
  "- **Requiredness.** No schema declares `required`. Which fields a create call actually demands is unknown.",
  "- **Writability.** Read-only vs request-only flags are unverified; the display-only fields listed under [field hazards](#readonly-hydrated-fields--medium) were inferred from response shape, not from a rejected write.",
  "- **Validation boundaries.** String lengths, numeric ranges and date bounds are undocumented.",
  "- **Create/update and soft-delete semantics** beyond the nested-entity PUT convention.",
  "- **Pagination limits** — `count` defaults to 100; the ceiling is unconfirmed.",
  "- **Nested item shapes** for `valueObjectOwnershipList`, `otherLoanPeople` and `assetLiabilityLinks`, which were empty in every sampled record.",
  "",
  "`Contact.webPassword` was observed in GET responses. Redact it at the wire",
  "boundary; it should not exist in any model a UI can reach.",
  "",
);

const mdPath = resolve(docsDir, "field-and-enum-reference.md");
writeFileSync(mdPath, md.join("\n").replace(/\n{3,}/g, "\n\n") + "\n");

// ───────────────────────── report ─────────────────────────

console.log(`Wrote ${jsonPath}`);
console.log(`Wrote ${mdPath}`);
console.log(
  `  ${s.enums} enums (${s.apiValidatedEnums} enforced, ${s.catalogOnlyEnums} catalog-only), ${s.enumValues} values`,
);
console.log(
  `  ${Object.keys(fieldIndex).length} fields indexed to a control (${s.enumBoundFields} enum-bound + ${s.softEnumFields} soft)`,
);
console.log(`  ${s.fields} fields across ${s.objectSchemas} object schemas`);
